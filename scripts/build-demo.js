// npm run build:demo
// Writes docs/data.js for the demo page, by running each example through the real pipeline (dry run).
import { writeFileSync } from "node:fs";
import { getConfig } from "../src/config.js";
import { loadPlaybooks } from "../src/playbooks.js";
import { runPipeline } from "../src/pipeline.js";
import { normalizeNote } from "../src/granola.js";
import { validateExtraction } from "../src/claude.js";
import { loadExamples, mockDeps } from "./examples.js";

const config = { ...getConfig({}), dryRun: true };
const playbooks = loadPlaybooks(config.playbooksDir);

const ORDER = ["sales-fjord", "am-casaverde", "mkt-kettle", "cs-sunpeak", "ops-atlas"];
const PB_ORDER = ["sales", "account-management", "marketing", "customer-success", "team-meeting"];
const rank = (list, id) => (list.indexOf(id) + 1 || 99);

const examples = [];
for (const ex of loadExamples().sort((a, b) => rank(ORDER, a.id) - rank(ORDER, b.id))) {
  const deps = mockDeps(ex, playbooks);
  const clean = validateExtraction(ex.output);
  deps.extract = async () => clean;
  const r = await runPipeline(ex.note, { config, playbooks, deps });
  const note = normalizeNote(ex.note);
  examples.push({
    id: ex.id,
    title: note.title,
    date: note.date,
    folder: note.folder,
    attendees: note.attendees,
    transcript: note.transcript,
    team: r.team,
    linearTeam: r.linearTeam,
    routedBy: r.routedBy,
    routeReason: r.routeReason,
    summary: r.summary,
    tasks: clean.tasks.map((t, i) => ({ ...t, flagged: r.planned[i].flagged, assigned: r.planned[i].assigneeEmail })),
  });
}

const data = {
  playbooks: [...playbooks].sort((a, b) => rank(PB_ORDER, a.id) - rank(PB_ORDER, b.id)).map(({ id, team, linearTeam, folders, description, instructions }) => ({ id, team, linearTeam, folders, description, instructions })),
  examples,
};
writeFileSync(new URL("../docs/data.js", import.meta.url), `// Generated by scripts/build-demo.js. Do not edit by hand.\nwindow.MINUTA = ${JSON.stringify(data, null, 1)};\n`);
console.log(`Wrote docs/data.js with ${examples.length} examples and ${playbooks.length} playbooks.`);
